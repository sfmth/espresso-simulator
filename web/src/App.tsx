import type { ReactNode } from 'react';
import { ModeTabs, panelId, tabId } from './components/ModeTabs';
import { Tabs } from './components/Tabs';
import { APP_VERSION, LICENSES_FILE, SOURCE_URL } from './config';
import { SphereVerificationPanel } from './lab/SphereVerificationPanel';
import { ShotLab } from './shot/ShotLab';
import { useAppStore, type LabView, type Mode } from './store';

function TabPanel({ mode, active, children }: { mode: Mode; active: Mode; children: ReactNode }) {
  // Inactive panels stay mounted (hidden), so their state and charts survive a tab switch.
  return (
    <section
      role="tabpanel"
      id={panelId(mode)}
      aria-labelledby={tabId(mode)}
      hidden={mode !== active}
      tabIndex={0}
      className="tab-panel"
    >
      {children}
    </section>
  );
}

function ComingSoon({
  title,
  milestone,
  children,
}: {
  title: string;
  milestone: string;
  children: ReactNode;
}) {
  return (
    <div className="coming-soon">
      <h2>{title}</h2>
      <p className="coming-soon-milestone">Coming in {milestone}</p>
      <p>{children}</p>
    </div>
  );
}

function Lab() {
  const view = useAppStore((s) => s.labView);
  const setView = useAppStore((s) => s.setLabView);
  return (
    <Tabs<LabView>
      idPrefix="lab"
      label="Lab views"
      className="lab-views"
      value={view}
      onChange={setView}
      tabs={[
        { id: 'shot', label: 'Shot lab', render: () => <ShotLab /> },
        {
          id: 'verification',
          label: 'Kernel verification',
          render: () => <SphereVerificationPanel />,
        },
      ]}
    />
  );
}

export function App() {
  const mode = useAppStore((s) => s.mode);
  const setMode = useAppStore((s) => s.setMode);

  return (
    <div className="app">
      <a className="skip-link" href="#main">
        Skip to content
      </a>
      <header className="app-header">
        <div className="brand">
          <h1>Puckworks</h1>
          <p className="tagline">Espresso simulator · M1.1 preview</p>
        </div>
        <ModeTabs mode={mode} onChange={setMode} />
      </header>

      <main id="main" className="app-main" tabIndex={-1}>
        <TabPanel mode="dial-in" active={mode}>
          <ComingSoon title="Dial-in" milestone="M4">
            Describe your beans, grinder, puck and machine to get a predicted shot, then calibrate
            the model to your own setup.
          </ComingSoon>
        </TabPanel>
        <TabPanel mode="lab" active={mode}>
          <Lab />
        </TabPanel>
        <TabPanel mode="explore" active={mode}>
          <ComingSoon title="Explore" milestone="M5">
            Look inside the puck: a 3D view of particles, flow and extraction over the shot.
          </ComingSoon>
        </TabPanel>
      </main>

      <footer className="app-footer">
        <span>GPL-2.0-or-later</span>
        <span>Nothing you enter leaves your browser</span>
        {SOURCE_URL ? (
          <a href={SOURCE_URL}>Source code</a>
        ) : (
          <span>Source code: not linked in this local build</span>
        )}
        {/* The notices file is generated by the production build only. */}
        {import.meta.env.PROD && <a href={`./${LICENSES_FILE}`}>Third-party licences</a>}
        <span>Version {APP_VERSION}</span>
      </footer>
    </div>
  );
}
